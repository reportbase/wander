def _flat(v):
    return list(v) if isinstance(v, (list, tuple)) else [v]

if __name__ == '__main__':
    bad = 0
    for L in LAWS:
        if L['verdict'] != 'notation':
            continue
        err = max(abs(a - b) for p in L['points'] for a, b in zip(_flat(L['orig'](p)), _flat(L['new'](p))))
        ok = err < mp.mpf('1e-30')
        bad += not ok
        print(L['n'], 'ok' if ok else 'FAIL', mp.nstr(err, 3))
    nn = sum(L['verdict'] == 'notation' for L in LAWS)
    print('laws', len(LAWS), 'notation', nn, 'NONE', len(LAWS) - nn, 'failures', bad)
